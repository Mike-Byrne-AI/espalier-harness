"""Single source of truth for the espalier:managed marker contract.

Espalier-Harness owns ("manages") files it deploys. The marker is the
ownership signal that lets ``espalier init`` distinguish files it
generated (safe to regenerate) from files a user authored (must be
preserved). The marker also lets cleanup, audit, and doctor identify
managed surface without reaching into deploy logic.

Public contract::

    if target does not exist:
        write file with managed marker
    if target exists and has_managed_marker(content):
        regenerate (overwrite with the new managed copy)
    if target exists and not has_managed_marker(content):
        preserve and report as a skipped user file

Marker placement rules:
- ``.md`` with YAML frontmatter → ``apply_marker_to_md`` inserts the
  HTML comment AFTER the closing ``---`` so frontmatter parsers (Claude
  Code agent loader, GitHub renderer, MkDocs) see a valid frontmatter
  block at the top of the file.
- ``.md`` without frontmatter → marker prepended at the top.
- ``.toml`` / ``.txt`` / ``.py`` → ``apply_marker_to_text`` prepends a
  ``# espalier:managed`` line (or after a ``#!`` shebang).
- ``.cmd`` (the Windows statusline shim) → ``apply_marker_to_batch`` inserts
  a ``:: espalier:managed`` line after a leading ``@echo off``: to cmd.exe a
  ``#`` line is a command, and a line before the echo-off is echoed to stdout,
  which is the statusline's channel.
- ``.json`` (settings.json) → no inline marker; the JSON sentinel key
  ``_espalier_managed`` (boolean ``true``) lives at the top level.

Centralizing these constants closes the duplication that previously
lived across handoff.py, managed_paths.py, proofs.py, render_surface.py,
and inline string literals in cli.py.
"""
