class TestHasManagedMarker:
    def test_recognizes_html_comment_at_top(self):
        text = f"<!-- {MANAGED_MARKER} -->\n# heading\n"
        assert has_managed_marker(text) is True

    def test_recognizes_hash_comment_at_top(self):
        text = f"# {MANAGED_MARKER}\nx = 1\n"
        assert has_managed_marker(text) is True

    def test_unmarked_returns_false(self):
        assert has_managed_marker("# unmanaged content\n") is False

    def test_empty_returns_false(self):
        assert has_managed_marker("") is False

    def test_recognizes_marker_after_short_frontmatter(self):
        text = (
            "---\nname: foo\nmodel: opus\n---\n"
            f"<!-- {MANAGED_MARKER} -->\n# body\n"
        )
        assert has_managed_marker(text) is True

    def test_recognizes_marker_after_long_frontmatter(self):
        # Build a frontmatter block ~1500 bytes long — well past the
        # default scan window, exercising the post-frontmatter padding.
        body = "\n".join(f"  field{i}: x" * 4 for i in range(100))
        text = (
            f"---\nname: foo\ndescription: |\n{body}\nmodel: opus\n---\n"
            f"<!-- {MANAGED_MARKER} -->\n# body\n"
        )
        assert has_managed_marker(text) is True

    def test_marker_buried_past_scan_window_not_detected(self):
        # No frontmatter, marker placed deep in the body — counts as a body
        # mention, not an ownership signal.
        padding = "x = 1\n" * 200
        text = f"{padding}# {MANAGED_MARKER}\n"
        assert has_managed_marker(text) is False

    def test_explicit_scan_chars_override(self):
        # Caller can request a wider scan window when needed.
        # 200 lines * 8 chars = 1600 chars padding — well past the default
        # 600-byte window but within an explicit 2000.
        text = "padding\n" * 200 + f"# {MANAGED_MARKER}\n"
        assert has_managed_marker(text) is False
        assert has_managed_marker(text, scan_chars=2000) is True


