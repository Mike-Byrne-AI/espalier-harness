class TestJsonSentinelIsRealSoT:
    """The settings sentinel must route through ``JSON_SENTINEL_KEY``, not a
    hardcoded ``"_espalier_managed"`` literal duplicated per reader/writer.

    An exported "single source of truth" constant that no reader imports is
    worse than the literal it claims to replace — it *claims* a centralization
    the code does not have. This pins the routing: every production
    reader/writer imports the constant, and the bare literal appears in NO
    espalier/ code outside ``managed_markers.py`` (its definer). Comments are
    exempt (not AST nodes); markdown assets and test fixtures keep the literal
    deliberately as independent oracles (a test routing through the constant
    would be circular).
    """

    @staticmethod
    def _repo_root() -> Path:
        return Path(__file__).resolve().parent.parent

    def test_production_readers_import_the_constant(self):
        root = self._repo_root()
        for mod in ("espalier/cli.py", "espalier/cleanup.py"):
            src = (root / mod).read_text(encoding="utf-8")
            assert "JSON_SENTINEL_KEY" in src, (
                f"{mod} must route the settings sentinel through "
                "JSON_SENTINEL_KEY, not a hardcoded literal"
            )

    @staticmethod
    def _sentinel_literal_lines(source: str) -> list[int]:
        """Line numbers where the sentinel literal appears as a string Constant
        in ``source``'s AST (comments/prose are not AST nodes, so exempt)."""
        tree = ast.parse(source)
        return [
            node.lineno
            for node in ast.walk(tree)
            if isinstance(node, ast.Constant)
            and isinstance(node.value, str)
            and node.value == "_espalier_managed"
        ]

    def test_scan_actually_fires_on_a_planted_literal(self):
        # Negative fixture: the absence assertion below is only meaningful if the
        # AST scan genuinely detects a hardcoded literal. Prove it fires on one
        # and does NOT fire on the routed constant — otherwise the gate is vacuous.
        assert self._sentinel_literal_lines('data["_espalier_managed"] = True') == [1]
        assert self._sentinel_literal_lines("data[JSON_SENTINEL_KEY] = True") == []

    def test_literal_appears_in_no_production_code(self):
        root = self._repo_root()
        offenders: list[str] = []
        scanned = 0
        for path in sorted((root / "espalier").rglob("*.py")):
            rel = path.relative_to(root).as_posix()
            if "/_vendor/" in f"/{rel}":
                continue  # tools mirror — governed by tools/cc rules
            if rel == "espalier/managed_markers.py":
                continue  # the definer legitimately owns the literal
            try:
                source = path.read_text(encoding="utf-8")
            except OSError:
                continue
            scanned += 1
            try:
                offenders += [f"{rel}:{ln}" for ln in self._sentinel_literal_lines(source)]
            except SyntaxError:
                continue
        # Scan-witness: without this, a broken walker (0 files) passes vacuously.
        assert scanned > 10, (
            f"walker visited only {scanned} espalier/*.py files — the absence "
            "assertion would be vacuous; the scan is broken"
        )
        assert not offenders, (
            "the settings sentinel literal is hardcoded in production code "
            f"instead of routing through JSON_SENTINEL_KEY: {offenders}"
        )


