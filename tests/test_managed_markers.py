class TestLineAnchoredRecognition:
    """The marker must match only as an anchored comment line.

    BC-026: a YAML scalar, prose paragraph, or JSON value referencing
    ``espalier:managed`` as text used to count as a marker (substring
    match). Hostile assets shipped via PR could thus impersonate
    managed files and become overwritable by ``espalier init``. The
    fix anchors recognition to ``^[ \\t]*(?:#|<!--|::)`` line starts (a shell,
    HTML or batch-file comment head).
    """

    def test_yaml_scalar_substring_rejected(self):
        text = "---\ndescription: compatible with espalier:managed projects\n---\nbody\n"
        assert has_managed_marker(text) is False

    def test_prose_paragraph_substring_rejected(self):
        text = "# title\n\nThis tool uses espalier:managed markers to track ownership.\n"
        assert has_managed_marker(text) is False

    def test_json_string_value_rejected(self):
        text = '{"description": "espalier:managed"}\n'
        assert has_managed_marker(text) is False

    def test_alternate_comment_char_rejected(self):
        assert has_managed_marker("// espalier:managed\nbody\n") is False
        assert has_managed_marker("; espalier:managed\nbody\n") is False
        assert has_managed_marker("/* espalier:managed */\nbody\n") is False

    def test_case_sensitive(self):
        assert has_managed_marker("# Espalier:Managed\n") is False
        assert has_managed_marker("# ESPALIER:MANAGED\n") is False

    def test_mid_line_marker_rejected(self):
        text = "some prefix # espalier:managed\nbody\n"
        assert has_managed_marker(text) is False

    def test_trailing_text_after_canonical_marker_ok(self):
        assert has_managed_marker("# espalier:managed extra commentary\n") is True

    def test_word_boundary_blocks_adjacent_alphanumeric(self):
        assert has_managed_marker("# espalier:managed42\n") is False
        assert has_managed_marker("# espalier:managedx\n") is False

    def test_leading_tab_tolerated(self):
        assert has_managed_marker("\t# espalier:managed\n") is True
        assert has_managed_marker("\t\t<!-- espalier:managed -->\n") is True

    def test_zero_width_space_as_leading_whitespace_rejected(self):
        text = "\u200b# espalier:managed\n"
        assert has_managed_marker(text) is True, (
            "ZWSP is default-ignorable (Cf) and must be stripped from file head, "
            "not treated as line-displacing content"
        )

    def test_canonical_hash_form_matches(self):
        assert has_managed_marker("# espalier:managed\n") is True

    def test_canonical_html_short_form_matches(self):
        assert has_managed_marker("<!-- espalier:managed -->\n") is True

    def test_canonical_batch_form_matches(self):
        assert has_managed_marker(":: espalier:managed\n") is True

    def test_canonical_html_rich_form_matches(self):
        text = (
            "<!-- espalier:managed - regenerated by `espalier init`; "
            "edit at your own risk -->\n"
        )
        assert has_managed_marker(text) is True


