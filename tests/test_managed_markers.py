class TestApplyMarkerToBatch:
    """DEF-729: the Windows statusline shim is a batch file. To cmd.exe a
    ``#`` line is a command, and every line before ``@echo off`` is echoed to
    stdout -- the statusline's own channel -- so the batch marker is ``::``
    and it goes on the line AFTER a leading echo-off."""

    def test_marker_lands_after_a_leading_echo_off(self):
        from espalier.managed_markers import MARKER_BATCH_COMMENT, apply_marker_to_batch, has_managed_marker

        result = apply_marker_to_batch("@echo off\nsetlocal\nrem x\n")
        lines = result.split("\n")
        assert lines[0] == "@echo off"
        assert lines[1] == MARKER_BATCH_COMMENT
        assert lines[2] == "setlocal"
        assert has_managed_marker(result)

    def test_echo_off_is_matched_the_way_cmd_reads_it(self):
        from espalier.managed_markers import MARKER_BATCH_COMMENT, apply_marker_to_batch

        result = apply_marker_to_batch("  @ECHO OFF\nx\n")
        assert result.split("\n")[1] == MARKER_BATCH_COMMENT

    def test_marker_goes_on_top_when_there_is_no_echo_off(self):
        from espalier.managed_markers import MARKER_BATCH_COMMENT, apply_marker_to_batch

        result = apply_marker_to_batch("python x.py\n")
        assert result.startswith(MARKER_BATCH_COMMENT + "\n")

    def test_idempotent(self):
        from espalier.managed_markers import apply_marker_to_batch

        once = apply_marker_to_batch("@echo off\nx\n")
        assert apply_marker_to_batch(once) == once

    def test_the_source_shim_carries_no_marker_and_the_deployed_copy_does(self):
        """The tools/cc/ source is the SoT and never carries a marker (its
        rem lines mention the marker only mid-line, which the anchored
        pattern must not read); the deploy inserts one."""
        from pathlib import Path

        from espalier.managed_markers import apply_marker_to_batch, has_managed_marker
        from espalier.managed_paths import STATUSLINE_SHIM

        source = (Path(__file__).resolve().parent.parent / STATUSLINE_SHIM).read_text(encoding="utf-8")
        assert not has_managed_marker(source)
        assert has_managed_marker(apply_marker_to_batch(source))


