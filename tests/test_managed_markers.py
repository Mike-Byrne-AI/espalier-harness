class TestApplyMarkerToMd:
    def test_no_frontmatter_marker_at_top(self):
        result = apply_marker_to_md("# title\nbody\n")
        assert result.startswith(MARKER_HTML_COMMENT_RICH)

    def test_frontmatter_marker_after_close(self):
        content = (
            "---\nname: foo\ndescription: bar\nmodel: opus\n---\n# Body\n"
        )
        result = apply_marker_to_md(content)
        # Frontmatter must remain intact at the top
        assert result.startswith("---\n")
        assert "name: foo" in result.split("\n---\n")[0]
        # Marker line is on the line after the closing ---
        head, _, tail = result.partition("\n---\n")
        assert tail.startswith(MARKER_HTML_COMMENT_RICH)

    # An EMPTY frontmatter breaks in two different places, so both rows below
    # fail for DIFFERENT reasons — which is the proof this is two branches, not
    # one. `---\n---\n`: the closing delimiter starts at index 3, but the search
    # began at 4, so the block read as "no frontmatter" and the marker was
    # PREPENDED above line 1, invalidating the YAML. `---\n---` (delimiter at
    # EOF, no trailing newline): the index is already correct, but `head` ends
    # in `---`, so the marker was GLUED onto the delimiter line.
    @pytest.mark.parametrize("body", ["---\n---\n", "---\n---"])
    def test_empty_frontmatter_marker_lands_below_the_closing_delimiter(self, body):
        out = apply_marker_to_md(body, comment="<!-- M -->")
        # Glue check FIRST: ordered this way each row reds on its OWN mechanism
        # (row 2 on the glue, row 1 on the prepend). With startswith first, row 2
        # short-circuits on it and the glue defect never gets named.
        assert "---<!-- M -->" not in out, out
        assert out.startswith("---\n---\n"), out

    def test_idempotent_no_double_insertion(self):
        text = "# already managed\n"
        once = apply_marker_to_md(text)
        twice = apply_marker_to_md(once)
        assert once == twice

    def test_idempotent_with_frontmatter(self):
        content = "---\nname: foo\nmodel: opus\n---\n# body\n"
        once = apply_marker_to_md(content)
        twice = apply_marker_to_md(once)
        assert once == twice

    def test_preserves_yaml_frontmatter_validity(self):
        # The agent loader parses YAML between the leading ---/--- pair.
        # Marker insertion must not introduce content before or inside
        # the frontmatter that would break parsing.
        content = "---\nname: r\ndescription: d\nmodel: opus\n---\nbody\n"
        result = apply_marker_to_md(content)
        # Opening delimiter still at byte 0
        assert result.startswith("---\n")
        # Closing delimiter still present and parseable
        end = result.find("\n---\n", 4)
        assert end > 0
        # Content between the two --- delimiters is byte-identical to the
        # original frontmatter (no smuggled marker line, no rewriting).
        original_frontmatter = content[:content.find("\n---\n", 4)]
        new_frontmatter = result[:end]
        assert new_frontmatter == original_frontmatter

    def test_custom_comment_form_used(self):
        result = apply_marker_to_md(
            "# x\n", comment=MARKER_HTML_COMMENT_SHORT,
        )
        assert result.startswith(MARKER_HTML_COMMENT_SHORT)
        assert MARKER_HTML_COMMENT_RICH not in result


