# Seed-version stamp — the CONTENT key for "harness-provenance, adopter-owned"
# ---------------------------------------------------------------------------


def _stamped(body: str, version: str = "0.8.0a13") -> str:
    import hashlib

    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    return f"<!-- espalier:seed-version v{version} sha256:{digest} -->\n{body}"


class TestSeedStamp:
    """DEF-686 / DEF-687: one owner for the seed stamp, readable without cli."""

    def test_cli_regex_is_the_same_object(self):
        from espalier import cli
        from espalier.managed_markers import SEED_STAMP_RE

        assert cli._SEED_STAMP_RE is SEED_STAMP_RE

    def test_digest_and_presence(self):
        from espalier.managed_markers import has_seed_stamp, seed_stamp_digest

        text = _stamped("# Doc\n")
        assert has_seed_stamp(text)
        assert seed_stamp_digest(text) == text.split("sha256:")[1].split(" ")[0]
        assert not has_seed_stamp("# Doc\n")
        assert seed_stamp_digest("# Doc\n") is None

    def test_managed_marker_is_not_a_seed_stamp(self):
        from espalier.managed_markers import MARKER_HTML_COMMENT_SHORT, has_seed_stamp

        assert not has_seed_stamp(MARKER_HTML_COMMENT_SHORT + "\n# Doc\n")

    def test_stamp_must_be_the_first_line(self):
        from espalier.managed_markers import has_seed_stamp

        assert not has_seed_stamp("\n" + _stamped("# Doc\n"))

    def test_untouched_vs_edited_vs_unstamped(self):
        from espalier.managed_markers import seed_is_untouched

        text = _stamped("# Conventions\n\n- one\n")
        assert seed_is_untouched(text)
        assert not seed_is_untouched(text + "- operator added a line\n")
        assert not seed_is_untouched("# Conventions\n\n- one\n")

    def test_path_predicate_reads_only_the_head(self, tmp_path: Path):
        from espalier.managed_markers import SEED_STAMP_SCAN_BYTES, path_has_seed_stamp

        big = tmp_path / "big.md"
        big.write_text(_stamped("x" * 300_000), encoding="utf-8")
        assert path_has_seed_stamp(big)
        # a long version string still fits the peek window
        longv = tmp_path / "longv.md"
        longv.write_text(_stamped("body\n", version="0.8.0a13.post1+local.build.9999"), encoding="utf-8")
        assert len(longv.read_text(encoding="utf-8").splitlines()[0]) < SEED_STAMP_SCAN_BYTES
        assert path_has_seed_stamp(longv)

    def test_path_predicate_refuses_what_it_cannot_read(self, tmp_path: Path):
        from espalier.managed_markers import path_has_seed_stamp

        assert not path_has_seed_stamp(tmp_path / "missing.md")
        assert not path_has_seed_stamp(tmp_path)  # a directory
        binary = tmp_path / "blob.md"
        binary.write_bytes(b"\x00\xff" * 40)
        assert not path_has_seed_stamp(binary)
        plain = tmp_path / "plain.md"
        plain.write_text("# Mine\n", encoding="utf-8")
        assert not path_has_seed_stamp(plain)

    def test_crlf_resave_is_still_a_stamp(self, tmp_path: Path):
        """Review catch: a Windows editor resaving a seed with CRLF (and/or a
        BOM) is not an edit. The byte-mode peek must fold line endings the way
        text-mode readers already do, or the seed re-enters the fingerprint."""
        from espalier.managed_markers import has_seed_stamp, path_has_seed_stamp, seed_is_untouched

        lf = _stamped("# Doc\n\nline\n")
        crlf = lf.replace("\n", "\r\n")
        bom_crlf = "\ufeff" + crlf
        for variant in (crlf, bom_crlf):
            assert has_seed_stamp(variant)
            assert seed_is_untouched(variant)
        f = tmp_path / "seed.md"
        f.write_bytes(crlf.encode("utf-8"))
        assert path_has_seed_stamp(f)
        f.write_bytes(bom_crlf.encode("utf-8"))
        assert path_has_seed_stamp(f)
