class TestConfusableDetection:
    """Loud-warning surface for visual-near-marker patterns.

    These do NOT match the anchored regex (so the file is treated as
    not-managed, which is the secure outcome). The warning catches the
    case where a maintainer's eye sees the confusable in a PR diff and
    approves it as if it were a real marker — at which point the asset
    would be silently not-managed and future ``espalier init`` reruns
    would skip it (silent disable).
    """

    def test_cyrillic_confusable_first_char_flagged(self):
        from espalier.managed_markers import find_confusable_markers
        content = "# \u0435spalier:managed\n"
        findings = find_confusable_markers(content)
        assert findings, "Cyrillic-first-char confusable not surfaced"

    def test_mid_word_cyrillic_flagged(self):
        from espalier.managed_markers import find_confusable_markers
        content = "# esp\u0430lier:managed\n"
        findings = find_confusable_markers(content)
        assert findings, "mid-word Cyrillic confusable not surfaced"

    def test_multiple_cyrillic_substitutions_flagged(self):
        from espalier.managed_markers import find_confusable_markers
        content = "# esp\u0430lier:m\u0430n\u0430ged\n"
        findings = find_confusable_markers(content)
        assert findings, "multi-Cyrillic confusable not surfaced"

    def test_uppercase_variant_flagged(self):
        from espalier.managed_markers import find_confusable_markers
        content = "# Espalier:Managed\n"
        findings = find_confusable_markers(content)
        assert findings, "case-variant confusable not surfaced (matches via mixed-case regex character classes)"

    def test_html_entity_flagged(self):
        from espalier.managed_markers import find_confusable_markers
        content = "# &#x65;spalier:managed\n"
        findings = find_confusable_markers(content)
        assert findings, "HTML-entity confusable not surfaced"

    def test_html_entity_decimal_flagged(self):
        from espalier.managed_markers import find_confusable_markers
        content = "# &#101;spalier:managed\n"
        findings = find_confusable_markers(content)
        assert findings, "decimal HTML-entity confusable not surfaced"

    def test_canonical_marker_not_flagged(self):
        from espalier.managed_markers import find_confusable_markers
        assert find_confusable_markers("# espalier:managed\n") == []
        assert find_confusable_markers("<!-- espalier:managed -->\n") == []

    def test_unrelated_content_not_flagged(self):
        from espalier.managed_markers import find_confusable_markers
        assert find_confusable_markers("# arbitrary heading\n") == []
        assert find_confusable_markers("") == []

    def test_findings_include_line_number(self):
        from espalier.managed_markers import find_confusable_markers
        content = "\n\n\n# \u0435spalier:managed\n"
        findings = find_confusable_markers(content)
        assert findings
        assert findings[0][1] == 4, (
            f"line number wrong: expected 4, got {findings[0][1]}"
        )

    def test_assets_have_no_confusables_at_release(self):
        """Contract test: shipped ``.md`` assets in ``espalier/assets/``
        must use canonical markers. Prevents a maintainer from
        accidentally shipping a confusable that would render the asset
        not-managed at recognition time.
        """
        from pathlib import Path

        from espalier.managed_markers import find_confusable_markers
        assets_dir = Path(__file__).parent.parent / "espalier" / "assets"
        offenders = []
        for path in assets_dir.rglob("*.md"):
            content = path.read_text(encoding="utf-8")
            confusables = find_confusable_markers(content)
            if confusables:
                offenders.append((path, confusables))
        assert not offenders, (
            "Shipped assets contain confusable markers:\n"
            + "\n".join(f"  {p}: {c}" for p, c in offenders)
        )

    def test_bom_prefix_does_not_demote_managed(self):
        """Round-2 finding (TP-54): a leading UTF-8 BOM would otherwise
        displace the ``^`` anchor and silently turn an existing managed
        file user-modified on next deploy."""
        canonical = "# espalier:managed\nbody\n"
        with_bom = "\ufeff" + canonical
        assert has_managed_marker(canonical) is True
        assert has_managed_marker(with_bom) is True, (
            "BOM-prefixed managed file silently demoted to user-modified"
        )

    @pytest.mark.parametrize("prefix", [
        "\ufeff",       # BOM (round-2)
        "\u200b",       # ZWSP (round-3)
        "\u200c",       # ZWNJ (round-3)
        "\u200d",       # ZWJ (round-3)
        "\u200e",       # LRM (round-3)
        "\u200f",       # RLM (round-3)
        "\u2028",       # LINE SEPARATOR (round-3)
        "\u2029",       # PARAGRAPH SEPARATOR (round-3)
        "\u202a",       # LEFT-TO-RIGHT EMBEDDING (round-3)
        "\u202e",       # RIGHT-TO-LEFT OVERRIDE (round-3)
        "\u2060",       # WORD JOINER (round-4; ZWSP successor)
        "\u2061",       # FUNCTION APPLICATION (round-4)
        "\u00ad",       # SOFT HYPHEN (round-4)
        "\u180e",       # MONGOLIAN VOWEL SEPARATOR (round-4)
        "\ufff9",       # INTERLINEAR ANNOTATION ANCHOR (round-4)
        "\u2066",       # LRI (round-4)
        "\u2069",       # PDI (round-4)
        "\ufeff\u200b\u2060",  # BOM + ZWSP + WORD JOINER combined
    ])
    def test_invisible_prefix_does_not_demote_managed(self, prefix):
        """Round-3/4 widening (TP-54 asymptote): not just BOM — ANY
        invisible / zero-width / bidi-control / default-ignorable
        codepoint at file start would displace the ``^`` anchor
        pre-fix."""
        canonical = "# espalier:managed\nbody\n"
        prefixed = prefix + canonical
        assert has_managed_marker(prefixed) is True, (
            f"Managed file silently demoted by invisible prefix "
            f"U+{ord(prefix[0]):04X}{'+...' if len(prefix) > 1 else ''}"
        )


