def _archive_members(tar_path: Path) -> set[str]:
    with tarfile.open(tar_path) as tf:
        return {m.name for m in tf.getmembers() if m.isfile()}


def _tracked_paths_at_head() -> set[str]:
    """Return paths in the HEAD commit tree.

    Distinct from :func:`_staged_tracked_paths` (the index) on purpose: this is
    the exact population ``git archive HEAD`` draws from, so a comparison of the
    two is apples-to-apples. Using the index instead would report a staged-but-
    uncommitted add as "pruned by git".

    ``check=True`` made rc 128 loud but left the OTHER empty case silent: inside
    a gitignored directory git answers rc 0 with zero rows, and every consumer
    here does a membership test against a denylist, which an empty set satisfies.
    Measured 2026-08-14 -- `test_unregistered_sentinel_hatch_is_untracked_only`
    went green under `dist/` and red outside it, same archive. §C21/`DEF-569`;
    the floor now lives in one place for all three consumers rather than being
    re-remembered per test (two of the three already had one, which is precisely
    how the third's absence stayed invisible).
    """
    return set(require_head_tree_paths(
        REPO_ROOT, minimum=_POPULATION_FLOOR, what="paths in the HEAD tree"
    ))


def _staged_tracked_paths() -> set[str]:
    """Return paths in the current git index (staged state). Reflects
    the post-commit state once changes are committed; useful for
    pre-commit validation when HEAD is older than the working tree.

    Floored for the same reason as :func:`_tracked_paths_at_head`, and this is
    the higher-consequence of the two: its sole consumer checks the 12-entry
    ``MUST_NOT_BE_IN_ARCHIVE`` denylist -- the gate against a kill-switched
    ``.claude/settings.json`` or an ``.espalier/integrity.json`` reaching the
    index -- and an empty set satisfies that check completely. §C21/`DEF-568`.
    """
    return set(require_tracked_paths(
        REPO_ROOT, minimum=_POPULATION_FLOOR, what="paths in the git index"
    ))


def test_staged_index_excludes_per_install_artifacts():
    """No gitignored runtime artifact may be staged for the next commit.

    This is the pre-commit signal: ``git ls-files`` reflects the index,
    so a leaked artifact shows up here BEFORE the commit lands.
    """
    staged = _staged_tracked_paths()
    leaks = sorted(rel for rel in MUST_NOT_BE_IN_ARCHIVE if rel in staged)
    assert not leaks, (
        "git index has per-install artifacts staged:\n  "
        + "\n  ".join(leaks)
        + "\n\nRemediation: git rm --cached <path> and verify "
        ".gitignore covers it; commit the change."
    )


def test_git_archive_head_excludes_per_install_artifacts(tmp_path):
    """``git archive HEAD`` is the release-shipping state; per-install
    artifacts must not appear there. Lags the index by one commit, so
    a fresh untrack only takes effect after the commit that records it.
    """
    tar_path = _git_archive_to_tar(tmp_path, "HEAD")
    members = _archive_members(tar_path)
    leaks = sorted(rel for rel in MUST_NOT_BE_IN_ARCHIVE if rel in members)
    assert not leaks, (
        "git archive HEAD leaked per-install artifacts:\n  "
        + "\n  ".join(leaks)
        + "\n\nRemediation: git rm --cached <path> and verify "
        ".gitignore covers it; commit the change."
    )


