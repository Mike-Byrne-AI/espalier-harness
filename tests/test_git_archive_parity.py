def _git_archive_to_tar(tmp_path: Path, ref: str, *, worktree_attributes: bool = False) -> Path:
    """Produce ``git archive <ref>`` as a tarball in ``tmp_path``.

    ``worktree_attributes=True`` adds ``--worktree-attributes`` so the archive
    honours the working-tree ``.gitattributes`` rather than the committed one —
    used to validate export-ignore rules before the ``.gitattributes`` commit
    lands (TP-171 §3.1).
    """
    tar_path = tmp_path / f"{ref.replace('/', '_')}.tar"
    cmd = ["git", "archive", "--format=tar"]
    if worktree_attributes:
        cmd.append("--worktree-attributes")
    cmd.append(ref)
    result = subprocess.run(
        cmd,
        cwd=str(REPO_ROOT),
        capture_output=True,
        check=True,
        timeout=60,
    )
    tar_path.write_bytes(result.stdout)
    return tar_path


