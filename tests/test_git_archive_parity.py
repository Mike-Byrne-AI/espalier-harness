def test_git_archive_ships_every_packaged_asset(tmp_path):
    """The COMPLEMENT of the export-ignore tests above — and the gap that let
    an unanchored rule prune a shipped package asset.

    Every test in this file so far enumerates what must NOT be in the archive.
    None asserts that what MUST ship actually does, so an ``export-ignore``
    pattern that over-reaches is invisible: the exclusion it was written for
    still works, the suite stays green, and the collateral casualty is only
    discovered by someone unpacking the artifact.

    ``espalier/assets/`` is the package payload ``espalier init`` deploys. A
    missing member there is not cosmetic — ``init`` from a GitHub "Download
    ZIP" dies mid-deploy with a bare ``Errno 2`` after writing a fraction of
    its files, leaving a half-initialized repo.

    Uses ``--worktree-attributes`` so the contract holds against the
    working-tree ``.gitattributes``, matching the sibling tests above.
    """
    result = subprocess.run(
        ["git", "ls-files", "espalier/assets/"],
        cwd=str(REPO_ROOT), capture_output=True, text=True, check=True, timeout=30, encoding="utf-8",
    )
    tracked = sorted(p for p in result.stdout.splitlines() if p)
    # Floor: the contract is vacuous if the asset tree moved or emptied out.
    # 51 tracked assets measured 2026-07-30; the floor guards a silent collapse
    # to zero, it is not a pin on the exact count.
    assert len(tracked) >= 51, (
        f"only {len(tracked)} tracked paths under espalier/assets/ — floor "
        "failed (asset tree moved or emptied?)"
    )

    tar_path = _git_archive_to_tar(tmp_path, "HEAD", worktree_attributes=True)
    members = _archive_members(tar_path)
    dropped = sorted(p for p in tracked if p not in members)
    assert not dropped, (
        "git archive (worktree-attributes) DROPPED packaged assets that "
        "`espalier init` needs:\n  " + "\n  ".join(dropped)
        + "\n\nRemediation: an export-ignore pattern is over-reaching. A rule "
        "meant for a top-level directory needs a LEADING SLASH "
        "(`/task-packs/`, not `task-packs/`) — without it git matches the "
        "directory name at ANY depth, including inside espalier/assets/."
    )


def test_surface_contract_matcher_agrees_with_git_on_every_tracked_path(tmp_path):
    """``surface_contract.matches_export_ignore`` must predict what git really
    prunes — checked against git, over the whole tracked tree.

    This is the gate that was missing when an unanchored ``task-packs/`` pruned
    ``espalier/assets/task-packs/CLAUDE.md`` from the archive. Three shipping
    consumers (``pre_release._find_internal_leaks``,
    ``release_pack``, ``scripts/build_release_archive.py``) ask that matcher
    what git will do, and *nothing* asked git whether the answer was right — so
    the model could disagree with the artifact indefinitely while every
    model-based check stayed green.

    Per-pattern unit assertions live in ``tests/test_pre_release.py``; this is
    the population-level complement. It is the only check here that compares the
    MODEL to the ARTIFACT rather than one artifact view to another.

    **Bounded, and the bound is measured.** Two mutations were driven against
    this test: dropping leading-slash anchoring reds it (naming
    ``espalier/assets/task-packs/CLAUDE.md`` exactly), but letting ``*`` cross
    ``/`` again leaves it GREEN — no tracked path currently exhibits that shape
    (``memory/`` is flat). A matcher defect only shows up here if the live tree
    happens to contain a path that triggers it, so this gate is a floor, never a
    proof of the matcher; the driven unit matrix is what covers the rest.
    """
    tracked = _tracked_paths_at_head()
    # Floor: vacuous if the tree listing broke or collapsed.
    assert len(tracked) >= 900, (
        f"only {len(tracked)} tracked paths at HEAD — floor failed"
    )

    tar_path = _git_archive_to_tar(tmp_path, "HEAD", worktree_attributes=True)
    members = _archive_members(tar_path)
    # Floor: the archive must be a subset of HEAD. A mangled member set (e.g.
    # from mis-parsing a --prefix that is not there) would otherwise read as a
    # huge, meaningless "git pruned everything" and could not fail honestly.
    stray = sorted(members - tracked)
    assert not stray, f"archive members absent from HEAD — probe broken: {stray[:5]}"

    patterns = surface_contract.export_ignore_patterns(REPO_ROOT)
    assert len(patterns) >= 8, (
        f"only {len(patterns)} export-ignore patterns parsed — floor failed"
    )

    disagreements = []
    for rel in sorted(tracked):
        model = any(surface_contract.matches_export_ignore(rel, p) for p in patterns)
        git_pruned = rel not in members
        if model != git_pruned:
            verb = "over-matches (model prunes, git ships)" if model else (
                "under-matches (model ships, git prunes)")
            disagreements.append(f"{rel}: {verb}")
    assert not disagreements, (
        "surface_contract.matches_export_ignore disagrees with git on "
        f"{len(disagreements)} of {len(tracked)} tracked paths:\n  "
        + "\n  ".join(disagreements[:20])
        + "\n\nRemediation: the matcher models git's export-ignore rules "
        "(leading-or-interior slash anchors to root; a trailing slash alone "
        "does not; export-ignore on a directory prunes its subtree; `*` never "
        "crosses `/`). An UNDER-match silently ships internal material; an "
        "OVER-match silently drops a file the payload needs."
    )


