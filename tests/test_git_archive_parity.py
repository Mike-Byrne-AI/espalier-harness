"""TP-53 source hygiene — git archive parity.

Pins the invariant that generated runtime artifacts never leak
into the source distribution. ``git archive HEAD`` must be a
faithful snapshot of "what git knows about" — nothing more,
nothing less. This guard prevents the "release zip contains files
git wouldn't" class of bug:

- ``.espalier/integrity.json`` (per-checkout, regenerated by
  ``espalier integrity refresh``) used to be tracked and produced
  spurious diffs after every refresh; TP-53 untracked it.
- ``.claude/settings.json`` (per-machine: it records the interpreter
  name detected on PATH) is gitignored — but if it ever drifts into
  the index, this test fires.
- ``reports/*.json`` are per-install fingerprints; same protection.

The test runs ``git archive`` into a temp dir, walks the extracted
tree, and asserts no entry from the gitignored-but-must-stay-
untracked set appears. Without this contract, a stray ``git add``
of one of these files would silently ship adopter-machine secrets
(absolute paths, integrity hashes) inside every source archive
release.
"""
