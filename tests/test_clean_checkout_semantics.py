class TestSourceCheckoutDoctor:
    def test_clean_checkout_passes(self, tmp_path):
        target = _source_checkout_target(tmp_path)
        report = run_doctor_check(target)
        assert report["mode"] == REPO_MODE_SOURCE_CHECKOUT
        assert report["status"] == "pass"
        assert not report["failures"]

    def test_clean_checkout_primary_reason_names_mode(self, tmp_path):
        target = _source_checkout_target(tmp_path)
        report = run_doctor_check(target)
        assert "source checkout" in report["primary_reason"].lower()

    def test_clean_checkout_info_explains_runtime_files(self, tmp_path):
        target = _source_checkout_target(tmp_path)
        report = run_doctor_check(target)
        info = " ".join(report.get("info", []))
        assert "settings.json" in info or "runtime" in info.lower()

    def test_missing_committed_surface_still_fails(self, tmp_path):
        # Source checkout WITH a committed-surface file deleted — this is
        # a real failure (source control should provide cc/COMMANDS.md).
        target = _source_checkout_target(tmp_path)
        (target / "cc" / "COMMANDS.md").unlink()
        report = run_doctor_check(target)
        assert report["status"] == "fail"
        assert any("COMMANDS.md" in f for f in report["failures"])


