# _detect_repo_mode — pure classifier
# ---------------------------------------------------------------------------


class TestDetectRepoMode:
    def test_empty_repo_is_uninitialized(self, tmp_path):
        target = _empty_target(tmp_path)
        assert _detect_repo_mode(target) == REPO_MODE_UNINITIALIZED

    def test_bare_reports_dir_is_still_uninitialized(self, tmp_path):
        """TP-152 E-5: a fresh adopter repo that keeps its own bare
        `reports/` dir (no espalier fingerprint artifact) must stay
        UNINITIALIZED. Pre-fix the bare dir was a runtime marker, flipping
        the repo out of the gentle-guidance path into a failure state."""
        target = _empty_target(tmp_path)
        (target / "reports").mkdir()
        (target / "reports" / "coverage.xml").write_text("x", encoding="utf-8")
        assert _detect_repo_mode(target) == REPO_MODE_UNINITIALIZED

    def test_clean_checkout_is_source_checkout(self, tmp_path):
        target = _source_checkout_target(tmp_path)
        assert _detect_repo_mode(target) == REPO_MODE_SOURCE_CHECKOUT

    def test_self_host_after_init_is_initialized_self_host(self, tmp_path):
        target = _initialized_self_host(tmp_path)
        assert _detect_repo_mode(target) == REPO_MODE_INITIALIZED_SELF_HOST

    def test_consumer_repo_after_init_is_initialized_consumer(self, tmp_path):
        # User repo (not espalier-harness) with init applied
        target = tmp_path / "user-repo"
        target.mkdir()
        (target / "README.md").write_text("# user\n", encoding="utf-8")
        (target / "pyproject.toml").write_text(
            '[project]\nname = "my-project"\n', encoding="utf-8",
        )
        subprocess.run(["git", "init", "-q", str(target)], check=True)
        subprocess.run(
            [sys.executable, "-m", "espalier.cli", "init", str(target)],
            check=True, capture_output=True, timeout=120,
        )
        assert _detect_repo_mode(target) == REPO_MODE_INITIALIZED_CONSUMER


