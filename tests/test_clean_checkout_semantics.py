class TestInitializedDoctor:
    def test_after_init_runs_full_checks(self, tmp_path):
        target = _initialized_self_host(tmp_path)
        report = run_doctor_check(target)
        assert report["mode"] == REPO_MODE_INITIALIZED_SELF_HOST
        # Every standard check present. The count is deliberately NOT restated
        # here: this comment read "All 5 standard checks" above a six-name
        # tuple, which is the same off-by-count drift the tuple exists to
        # catch, sitting inside the pin. `docs/TROUBLESHOOTING.md`'s prose count
        # is derived from the payload by
        # tests/test_troubleshooting_enumerations.py::TestDoctorCheckRoster.
        for check in ("presence", "audit", "reflect", "recover", "diff", "self_host"):
            assert check in report["checks"]


