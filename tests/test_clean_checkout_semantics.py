class TestExplicitModeOverride:
    def test_explicit_source_checkout_on_clean_clone_via_cli(self, tmp_path):
        target = _source_checkout_target(tmp_path)
        result = subprocess.run(
            [sys.executable, "-m", "espalier.cli", "doctor",
             str(target), "--mode", "source-checkout"],
            capture_output=True, text=True, timeout=60, encoding="utf-8",
        )
        assert result.returncode == 0
        report = json.loads(result.stdout)
        assert report["mode"] == REPO_MODE_SOURCE_CHECKOUT

    def test_explicit_initialized_on_clean_clone_fails_loudly(self, tmp_path):
        # Forcing initialized mode on a source checkout exposes the missing
        # runtime files as the real failure they would be in that mode.
        target = _source_checkout_target(tmp_path)
        result = subprocess.run(
            [sys.executable, "-m", "espalier.cli", "doctor",
             str(target), "--mode", "initialized"],
            capture_output=True, text=True, timeout=60, encoding="utf-8",
        )
        assert result.returncode == 1, (
            f"forced initialized mode on a clean clone should fail; got rc={result.returncode}"
        )
        report = json.loads(result.stdout)
        # Primary reason names a missing runtime file
        primary = report["primary_reason"]
        assert ("settings.json" in primary
                or "reports/" in primary
                or "managed surface" in primary.lower())


# ---------------------------------------------------------------------------
# The fixture's own cleanliness (DEF-481)
# ---------------------------------------------------------------------------


def _files_under(root: Path) -> set[str]:
    """Every file or symlink below ``root`` except ``.git/``, never following links."""
    found: set[str] = set()
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d != ".git"]
        rel_dir = Path(dirpath).relative_to(root)
        for name in filenames:
            found.add((rel_dir / name).as_posix())
        for name in dirnames:
            if os.path.islink(os.path.join(dirpath, name)):
                found.add((rel_dir / name).as_posix())
    return found


class TestSourceCheckoutTargetIsClean:
    """The copy the classes above call clean is exactly what a fresh clone has.

    Checked against `git ls-files` in BOTH directions -- nothing rode in that
    a clone lacks, nothing a clone has was left out -- so it runs on every
    tree the fixture runs on and never skips. The two pins this replaces
    certified a hand-kept exclusion set and skipped wherever the live
    artifacts were absent, which was every CI checkout (DEF-481).
    """

    def test_the_copy_is_exactly_the_tracked_set(self, tmp_path):
        tracked = set(require_tracked_paths(REPO_ROOT, minimum=200, what="tracked files"))
        target = _source_checkout_target(tmp_path)
        copied = _files_under(target)
        residue = sorted(copied - tracked)
        missing = sorted(tracked - copied)
        assert residue == [], f"untracked residue in the clean copy: {residue[:10]}"
        assert missing == [], f"tracked files missing from the clean copy: {missing[:10]}"
