"""TP-06 — repo-mode classifier + source-checkout doctor semantics.

A clean source checkout (committed surface present, no runtime artifacts)
must not fail doctor — the gitignored runtime files (`.claude/settings.json`,
`reports/*.json`, `.espalier/integrity.json`) are generated by `init`, not
required source files. CI runs doctor on fresh clones; this contract
guarantees those invocations exit 0.

Initialized repos still get the full check; partial init is still a real
failure.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

from espalier.doctor import (
    REPO_MODE_INITIALIZED_CONSUMER,
    REPO_MODE_INITIALIZED_SELF_HOST,
    REPO_MODE_SOURCE_CHECKOUT,
    REPO_MODE_UNINITIALIZED,
    _detect_repo_mode,
    run_doctor_check,
)

from tests._git_oracle import require_tracked_paths

REPO_ROOT = Path(__file__).resolve().parent.parent

# Marker assignment lives in tests/conftest.py::_MARKER_RULES.


def _empty_target(tmp_path: Path) -> Path:
    target = tmp_path / "empty"
    target.mkdir()
    return target


def _source_checkout_target(tmp_path: Path) -> Path:
    """Mirror the espalier-harness repo as a fresh `git clone` has it.

    Derived, not listed: the copy is exactly the tracked set -- `git ls-files`
    through the tree's git oracle, so a foreign or empty answer raises instead
    of yielding a hollow tree that still passes -- plus a fresh `git init`.
    Until 2026-09-13 this was a copytree over the working tree with a hand-kept
    exclusion list, and every "clean" copy carried 267 untracked files (the
    blueprint chain, the bench results, session state, nested caches), because
    a two-segment name in a root-only set never matches a directory listing
    (DEF-481). Symlinks are copied as links, never followed.
    """
    tracked = require_tracked_paths(REPO_ROOT, minimum=200, what="tracked files")
    target = tmp_path / "tree"
    for rel in tracked:
        dst = target / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(REPO_ROOT / rel, dst, follow_symlinks=False)
    subprocess.run(["git", "init", "-q"], cwd=str(target), check=True)
    return target


def _initialized_self_host(tmp_path: Path) -> Path:
    """A source-checkout target with `espalier init .` applied."""
    target = _source_checkout_target(tmp_path)
    subprocess.run(
        [sys.executable, "-m", "espalier.cli", "init", "."],
        cwd=str(target), check=True, capture_output=True, timeout=120,
    )
    return target


